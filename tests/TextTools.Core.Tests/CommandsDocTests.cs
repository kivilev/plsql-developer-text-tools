using System.Globalization;
using System.Text;

namespace TextTools.Core.Tests;

/// <summary>
/// docs/commands.md is generated from Commands.All, so the reference can never drift from the code.
/// After changing commands: set UPDATE_DOCS=1 and run the tests once to rewrite the file, then review the diff.
/// </summary>
public class CommandsDocTests
{
    /// <summary>The moment used for the "Now" examples.</summary>
    /// <remarks>Matches the menu captions: 2026-10-13 14:30:00.123456 -03:00.</remarks>
    private static readonly DateTimeOffset ExampleNow = new DateTimeOffset(2026, 10, 13, 14, 30, 0, TimeSpan.FromHours(-3)).AddTicks(1_234_560);

    [Fact]
    public void CommandsReferenceIsUpToDate()
    {
        var path = Path.Combine(RepoRoot(), "docs", "commands.md");
        var expected = Render();
        if (string.Equals(Environment.GetEnvironmentVariable("UPDATE_DOCS"), "1", StringComparison.Ordinal))
        {
            File.WriteAllText(path, expected, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        }
        var actual = File.Exists(path) ? File.ReadAllText(path).ReplaceLineEndings("\n") : "";
        Assert.True(string.Equals(expected, actual, StringComparison.Ordinal),
            "docs/commands.md is out of date: run the tests with UPDATE_DOCS=1 and commit the file");
    }

    [Fact]
    public void EveryTransformCommandHasASample() =>
        Assert.All(Commands.All.OfType<TransformCommand>(), c => Assert.NotNull(c.Sample));

    internal static string Render()
    {
        var sb = new StringBuilder();
        sb.Append("# Commands\n\n");
        sb.Append("<!-- Generated by tests/TextTools.Core.Tests/CommandsDocTests.cs from Commands.All. Do not edit by hand. -->\n\n");
        sb.Append("Select text in a PL/SQL Developer editor and pick a command under **Plug-Ins**. ");
        sb.Append("Without a selection a command applies to the whole text; \"Now\" commands insert at the cursor.\n");
        sb.Append("SQL Tools do not change the editor: the result goes to the clipboard (without a selection: the statement under the cursor).\n");
        sb.Append("Lines are separated by `⏎` in the examples below.\n");

        foreach (var menu in Commands.All.GroupBy(c => c.Menu, StringComparer.Ordinal))
        {
            sb.Append(CultureInfo.InvariantCulture, $"\n## {menu.Key}\n");
            foreach (var group in menu.GroupBy(c => c.Group, StringComparer.Ordinal))
            {
                sb.Append(CultureInfo.InvariantCulture, $"\n### {group.Key}\n\n| Command | Example input | Result |\n|---|---|---|\n");
                foreach (var cmd in group)
                {
                    var (input, output) = cmd switch
                    {
                        TransformCommand t => (t.Sample ?? "", t.Transform(t.Sample ?? "")),
                        InsertCommand i => ("(cursor position)", i.Format(ExampleNow)),
                        CopyCommand c => (c.Sample, c.SampleResult),
                        _ => ("", ""),
                    };
                    sb.Append(CultureInfo.InvariantCulture, $"| {Cell(cmd.Name, code: false)} | {Cell(input, code: cmd is TransformCommand or CopyCommand)} | {Cell(output, code: true)} |\n");
                }
            }
        }
        return sb.ToString();
    }

    private static string Cell(string text, bool code)
    {
        var s = text.Replace("\r\n", "\n", StringComparison.Ordinal).Replace("\n", " ⏎ ", StringComparison.Ordinal)
            .Replace("|", "\\|", StringComparison.Ordinal);
        if (!code) return s;
        return s.Contains('`', StringComparison.Ordinal) ? $"``{s}``" : $"`{s}`";
    }

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "TextTools.slnx")))
        {
            dir = dir.Parent;
        }
        return dir?.FullName ?? throw new InvalidOperationException("repository root (TextTools.slnx) not found");
    }
}
